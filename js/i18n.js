  function fill(template, vars) {
    if (!vars) return template;
    return template.replace(/\{(\w+)\}/g, function (_, name) {
      return vars[name] == null ? "" : String(vars[name]);
    });
  }

  window.wwT = function (key, vars) {
    const pack = current() === "zh-HK" ? zh : en;
    let value = Object.prototype.hasOwnProperty.call(pack, key) ? pack[key] : undefined;
    if (value == null && Object.prototype.hasOwnProperty.call(en, key)) value = en[key];
    if (value == null) return key;
    return fill(value, vars);
  };

